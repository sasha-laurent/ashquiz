/** Libellé de datation affiché après correction : « 1503-1519 » ou « 1893 ». */
export function dateLabel(painting) {
  return painting.yearEnd && painting.yearEnd !== painting.year
    ? `${painting.year}-${painting.yearEnd}`
    : String(painting.year);
}
